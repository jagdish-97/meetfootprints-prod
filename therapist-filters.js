/* Lookup helper used by therapist-profile.js (same name matching as script.js). */
window.findTherapistFilterInfo = function (therapistName) {
    var normalize = function (value) {
        return String(value || "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase()
            .replace(/\b1099\b/g, " ").replace(/[^a-z\s()-]/g, " ").replace(/-/g, " ").replace(/\s+/g, " ").trim();
    };
    var variants = function (value) {
        var n = normalize(value);
        var out = [n.replace(/\([^)]*\)/g, " ").replace(/\s+/g, " ").trim()];
        (n.match(/\(([^)]*)\)/g) || []).forEach(function (g) {
            var inner = g.replace(/[()]/g, "").trim();
            if (inner.split(" ").length > 1) { out.push(inner); }
        });
        return out.filter(Boolean).map(function (x) { return x.split(" ").filter(Boolean); });
    };
    var records = Array.isArray(window.THERAPIST_FILTER_DATA) ? window.THERAPIST_FILTER_DATA : [];
    var index = records.map(function (r) {
        var names = [r.name].concat(Array.isArray(r.aliases) ? r.aliases : []);
        return { record: r, variants: [].concat.apply([], names.map(variants)) };
    });
    var targets = variants(therapistName);
    var exact = function (a, b) { return a.join(" ") === b.join(" "); };
    var firstLast = function (a, b) { return a.length > 1 && b.length > 1 && a[0] === b[0] && a[a.length - 1] === b[b.length - 1]; };
    var containsAll = function (a, b) { return a.length > 1 && b.length > 1 && a[0] === b[0] && b.every(function (t) { return a.indexOf(t) !== -1; }); };
    var similarLast = function (a, b) { return a.length > 1 && b.length > 1 && a[0] === b[0] && a[a.length - 1].slice(0, 3) === b[b.length - 1].slice(0, 3); };
    var matchers = [exact, firstLast, containsAll, function (a, b) { return containsAll(b, a); }, similarLast];
    for (var m = 0; m < matchers.length; m++) {
        for (var i = 0; i < index.length; i++) {
            var hit = index[i].variants.some(function (v) { return targets.some(function (t) { return matchers[m](t, v); }); });
            if (hit) { return index[i].record; }
        }
    }
    return null;
};

